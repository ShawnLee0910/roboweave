#!/usr/bin/env python3
"""Finish construction compilation inside one package, using measured captures.

CPU-only. Captures must be generated by the registered construction-only lane.
No simulator launch, object placement, navigation implementation or standalone overlay.
"""
import argparse
from collections import defaultdict
from copy import deepcopy
import json
from pathlib import Path
import shutil

import compile_perception_reset_pose_candidates as selector
from behavior_hl.embodied.evaluator_bridge.l0_reset_pose_overlay import (
    OVERLAY_VERSION, patch_scene_template_reset_pose, patch_tro_state_reset_pose,
)

l0 = selector.l0


def reference(path):
    return {'path': str(path.resolve()), 'sha256': l0._sha256(path)}


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n')


def measured_task(record, capture, contract):
    if (capture.get('schema_version') != 'registered-initial-state-capture/v1'
            or capture.get('task_spec_id') != record['task_spec_id']
            or capture.get('source_template_sha256') != record['template']['sha256']
            or capture.get('source_contract_sha256') != record['template_contract']['sha256']):
        raise ValueError('capture identity or source mismatch')
    leaves = record['profile']['canonical_goal_leaves']
    truths = capture['initial_goal_leaf_truth']
    if capture['goal_leaves'] != leaves or len(truths) != len(leaves) or any(type(v) is not bool for v in truths) or all(truths):
        raise ValueError('invalid initial goal evidence')
    geometry = capture['scope_geometry']
    if contract.get('camera_relative_orientations') and not capture.get('camera_pose_capture'):
        raise ValueError('camera-relative poses require measured camera capture')
    bindings = contract['scope_bindings']
    required = {s for s, b in bindings.items() if b.get('binding_kind') != 'RUNTIME_ROBOT'}
    if set(geometry) != required:
        raise ValueError('incomplete measured geometry')
    for scope, g in geometry.items():
        if g['actual_name'] != bindings[scope]['actual_name']:
            raise ValueError('measured geometry binding mismatch')
        for key, size in [('position', 3), ('orientation', 4), ('aabb_min', 3), ('aabb_max', 3)]:
            values = g[key]
            if len(values) != size or not all(l0.math.isfinite(x) for x in values):
                raise ValueError('non-finite measured geometry')
        if abs(sum(x*x for x in g['orientation']) - 1.) > 1.e-5 or any(a > b for a, b in zip(g['aabb_min'], g['aabb_max'])):
            raise ValueError('invalid measured quaternion or bounds')
    plan = l0.compile_grounded_mixed_option(tuple(leaves),
        initially_true_relations=tuple(leaf for leaf, truth in zip(leaves, truths) if truth))
    return dict(task_spec_id=record['task_spec_id'], task_name=record['activity_name'],
        camera_pose_rules={contract['role_to_scope'][r]: rule for r, rule in contract.get('camera_relative_orientations', {}).items()},
        measured_geometry=geometry, camera_pose_capture=capture.get('camera_pose_capture'),
        family_id=record['source_family_id'], scene_model=record['scene_model'], rooms=record['rooms'],
        scope_bindings=bindings, positions={s: g['position'] for s, g in geometry.items()},
        operations=l0._plan_operations(plan), visibility_roles=selector.visibility_roles(bindings),
        proxy_scopes=[], initial_goal_false_cpu=True)


def freeze_documents(template, tro, capture, contract, selected):
    """Use complete measured object states (including joints), not pose-only resets."""
    template, tro = deepcopy(template), deepcopy(tro)
    original_states = template['state']['registry']['object_registry']
    measured = capture['scene_document']['state']['registry']['object_registry']
    for geometry in capture['scope_geometry'].values():
        root = measured[geometry['actual_name']]['root_link']
        if any(abs(a-b) > 1.e-5 for a, b in zip(root['pos'], geometry['position'])):
            raise ValueError('snapshot and geometry positions disagree')
    for name in original_states:
        if name not in measured:
            raise ValueError('capture lacks template object state: ' + name)
        original_states[name] = deepcopy(measured[name])
    for scope, binding in contract['scope_bindings'].items():
        if binding.get('binding_kind') != 'RUNTIME_ROBOT':
            tro[scope] = deepcopy(measured[binding['actual_name']])
    overlay = dict(schema_version=OVERLAY_VERSION, task_spec_id=selected['task_spec_id'],
        task_name=selected['task_spec_id'], fixed_robot_pose=selected['fixed_robot_pose'],
        initial_camera_view_state=selected['initial_camera_view_state'])
    return patch_scene_template_reset_pose(template, overlay), patch_tro_state_reset_pose(tro, overlay)


def finalize(source, capture_index, output, assets_root, robot_metadata, max_cells=64):
    source, output = source.resolve(), output.resolve()
    if output.exists() or output.is_relative_to(source):
        raise ValueError('output must be new and outside source package')
    package = l0._read_json(source / 'package.json')
    if package.get('purpose') == 'CALIBRATION_ONLY':
        raise ValueError('calibration specimens cannot be promoted to frozen tasks')
    for field in (package['task_specs'], package['runtime']['registration_catalog']):
        if l0._sha256(Path(field['path'])) != field['sha256']:
            raise ValueError('package source reference changed')
    catalog = l0._read_json(Path(package['runtime']['registration_catalog']['path']))
    if any(r.get('construction', {}).get('calibration_only') for r in catalog['tasks']):
        raise ValueError('calibration specimens cannot be promoted to frozen tasks')
    if [r['task_spec_id'] for r in catalog['tasks']] != package['task_spec_ids']:
        raise ValueError('package and catalog membership mismatch')
    captures, rejected_captures = {}, []
    for ref in l0._read_jsonl(capture_index):
        path = Path(ref['path'])
        if not path.is_absolute():
            path = capture_index.parent / path
        report = l0._read_json(path)
        if report.get('construction_pass') is not True:
            rejected_captures.append(reference(path))
            continue
        capture = report['initial_state_capture']
        task_id = capture['task_spec_id']
        if task_id in captures:
            raise ValueError('duplicate capture: ' + task_id)
        captures[task_id] = capture
    if set(captures) - set(package['task_spec_ids']):
        raise ValueError('capture membership contains unknown tasks')
    if not captures:
        raise ValueError('capture membership is empty')
    groups, contracts = defaultdict(list), {}
    for record in catalog['tasks']:
        for key in ('template', 'tro_state', 'template_contract', 'bddl'):
            if l0._sha256(Path(record[key]['path'])) != record[key]['sha256']:
                raise ValueError('source runtime file changed')
        task_id = record['task_spec_id']
        contract = l0._read_json(Path(record['template_contract']['path']))
        contracts[task_id] = contract
        groups[record['source_family_id']].append(record)
    selected, maps, documents = {}, {}, {}
    for family, records in sorted(groups.items()):
        ids = [r['task_spec_id'] for r in records]
        try:
            if any(task_id not in captures for task_id in ids):
                raise ValueError('family capture incomplete')
            tasks = [measured_task(r, captures[r['task_spec_id']], contracts[r['task_spec_id']]) for r in records]
            scene = tasks[0]['scene_model']
            if any(t['scene_model'] != scene for t in tasks):
                raise ValueError('family spans scenes')
            if scene not in maps:
                maps[scene] = l0.SceneMaps(scene_model=scene, assets_root=assets_root,
                    room_categories_path=assets_root / 'metadata/room_categories.txt', robot_metadata_path=robot_metadata)
            rows = selector.compile_family(tasks, maps[scene], max_cells)
            if {r['task_spec_id'] for r in rows} != set(ids) or any(not r['fixed_robot_pose'] for r in rows):
                raise ValueError('family has no shared initial pose')
            by_id = {r['task_spec_id']: r for r in rows}
            family_documents = {r['task_spec_id']: freeze_documents(
                l0._read_json(Path(r['template']['path'])), l0._read_json(Path(r['tro_state']['path'])),
                captures[r['task_spec_id']], contracts[r['task_spec_id']], by_id[r['task_spec_id']]) for r in records}
            documents.update(family_documents)
        except (ValueError, RuntimeError, KeyError) as exc:
            rows = [dict(task_spec_id=task_id, source_family_id=family,
                         fixed_robot_pose=None, failure_reasons=[str(exc)]) for task_id in ids]
        for row in rows:
            row.update(evidence_level='LIVE_CONSTRUCTED_GEOMETRY_STATIC_CAMERA_PREDICTION',
                route_model='GOAL_DAG_WITH_LIVE_INITIAL_TRUTH',
                selection_status='FROZEN_PENDING_RENDER' if row['fixed_robot_pose'] else 'INITIAL_STATE_COMPILE_FAILED',
                runtime_enabled=bool(row['fixed_robot_pose']))
            selected[row['task_spec_id']] = row
    # The source package remains immutable; only complete families enter the runnable subset.
    output.mkdir(parents=True)
    write(output / 'initial_state/compilation_report.json', list(selected.values()))
    write(output / 'initial_state/rejected_capture_reports.json', rejected_captures)
    source_ids = list(package['task_spec_ids'])
    ready_ids = [task_id for task_id in source_ids if selected[task_id]['runtime_enabled']]
    package['source_package'] = reference(source / 'package.json')
    package['deferred_task_spec_ids'] = [task_id for task_id in source_ids if task_id not in ready_ids]
    package.setdefault('evidence', {})['initial_state_compilation_report'] = reference(output / 'initial_state/compilation_report.json')
    if not ready_ids:
        package['initial_state_compilation'] = dict(required=True, status='FAILED')
        package['stage'] = 'CONSTRUCTION_PENDING'
        write(output / 'package.json', package)
        return {'status': 'FAILED', 'task_count': len(selected), 'output': str(output)}
    catalog['tasks'] = [r for r in catalog['tasks'] if r['task_spec_id'] in ready_ids]
    catalog['task_count'] = len(ready_ids)
    package['task_spec_ids'] = ready_ids
    package['task_count'] = len(ready_ids)
    for record in catalog['tasks']:
        task_id = record['task_spec_id']
        capture, row, contract = captures[task_id], selected[task_id], contracts[task_id]
        template, tro = documents[task_id]
        for key, value in [('template', template), ('tro_state', tro)]:
            target = output / 'runtime_registration' / key / task_id / Path(record[key]['path']).name
            write(target, value)
            record[key] = reference(target)
        for key in ('bddl', 'template_contract'):
            target = output / 'runtime_registration' / key / task_id / Path(record[key]['path']).name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(record[key]['path'], target)
            record[key] = reference(target)
        record['construction']['robot_start'] = deepcopy(row['fixed_robot_pose'])
        record['construction']['initial_camera_view_state'] = row['initial_camera_view_state']
        record['construction']['parked_before_live_construction'] = False
        record['construction']['live_aabb_construction_required'] = False
        record['construction']['frozen_initial_state'] = dict(schema_version='registered-frozen-initial-state/v1',
            scope_geometry=capture['scope_geometry'], initial_goal_leaf_truth=capture['initial_goal_leaf_truth'])
    catalog['live_run_ready'] = False
    catalog['live_blocker'] = 'FROZEN_RESET_RGB_MARKER_AND_LIVE_ROUTE_VALIDATION_NOT_RUN'
    write(output / 'runtime_registration/catalog.json', catalog)
    records_by_id = {r['task_spec_id']: r for r in catalog['tasks']}
    specs = [s for s in l0._read_jsonl(Path(package['task_specs']['path'])) if s['task_spec_id'] in ready_ids]
    for spec in specs:
        record = records_by_id[spec['task_spec_id']]
        private = spec.setdefault('private_runtime', {})
        private.update(robot_start=deepcopy(record['construction']['robot_start']),
            initial_view=deepcopy(record['construction']['initial_camera_view_state']),
            initial_state_status='FROZEN',
            frozen_initial_state=deepcopy(record['construction']['frozen_initial_state']))
    (output / 'task_specs.jsonl').write_text(''.join(json.dumps(s, ensure_ascii=False) + '\n' for s in specs))
    package['runtime']['registration_catalog'] = reference(output / 'runtime_registration/catalog.json')
    package['task_specs'] = reference(output / 'task_specs.jsonl')
    if package.get('visual_pairs'):
        pair_ref = package['visual_pairs']['bindings']
        pair_path = Path(pair_ref['path'])
        if l0._sha256(pair_path) != pair_ref['sha256']:
            raise ValueError('visual pair binding source changed')
        pairs = l0._read_jsonl(pair_path)
        for pair in pairs:
            if pair['base_task_spec_id'] in records_by_id and 'construction_dependency' in pair:
                pair['failures'] = [r for r in pair['failures'] if r != 'BASE_FROZEN_STATE_REQUIRED']
                pair['construction_dependency']['frozen_task_specs'] = package['task_specs']
        target = output / 'visual_pair_bindings.jsonl'
        target.write_text(''.join(json.dumps(r, ensure_ascii=False) + '\n' for r in pairs))
        package['visual_pairs']['bindings'] = reference(target)
        package['visual_pairs']['status'] = 'BOUND_PENDING_VISUAL_TRANSFORM_AND_REVIEW'
    package['initial_state_compilation'] = dict(required=True, status='FROZEN',
        reset_mode='RESTORE_AND_VERIFY_NO_RECONSTRUCTION', render_status='NOT_RUN', oracle_status='NOT_RUN')
    package['stage'] = 'COMPILED'
    package['live_run_ready'] = False
    package['live_blockers'] = ['FROZEN_RESET_RGB_MARKER_AND_LIVE_ROUTE_VALIDATION_NOT_RUN']
    write(output / 'package.json', package)
    return {'status': 'FROZEN_PENDING_RENDER', 'task_count': len(ready_ids),
            'deferred_task_count': len(source_ids) - len(ready_ids), 'output': str(output)}


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    for arg in ('source', 'capture-index', 'output', 'assets-root', 'robot-metadata'):
        p.add_argument('--' + arg, type=Path, required=True)
    a = p.parse_args()
    result = finalize(a.source, a.capture_index, a.output, a.assets_root, a.robot_metadata)
    print(json.dumps(result))
    raise SystemExit(0 if result['status'] == 'FROZEN_PENDING_RENDER' else 2)
